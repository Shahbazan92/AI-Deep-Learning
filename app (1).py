@st.cache_resource
def load_model():
    if not MODEL_PATH.exists():
        raise FileNotFoundError("Add skin_cancer_detector.keras to the same GitHub folder as app.py.")
    return tf.keras.models.load_model(MODEL_PATH)

st.markdown('<div class="section">How it works</div><div class="sub">Three simple steps powered by your trained CNN.</div>', unsafe_allow_html=True)
a,b,c=st.columns(3)
for col, title, desc, emoji in [
    (a,"01 · Upload image","Choose a JPG, JPEG or PNG image.","📤"),
    (b,"02 · CNN analysis","Your image is resized and passed to the trained model.","🧠"),
    (c,"03 · View prediction","Review the predicted class and model confidence.","📊")]:
    with col:
        st.markdown(f'<div class="card"><div style="font-size:24px">{emoji}</div><b>{title}</b><p style="color:#718096;font-size:13px">{desc}</p></div>',unsafe_allow_html=True)

st.markdown('<div class="section">Skin image analysis</div><div class="sub">Upload an image to run the classifier.</div>',unsafe_allow_html=True)
left,right=st.columns([1,1],gap="large")
with left:
    st.markdown('<div class="card">',unsafe_allow_html=True)
    st.subheader("Upload your image")
    uploaded=st.file_uploader("Select a skin image",type=["jpg","jpeg","png"])
    preview=None
    if uploaded:
        try:
            preview=Image.open(uploaded).convert("RGB")
            st.image(preview,caption="Image selected",use_container_width=True)
        except Exception:
            st.error("Could not open this image.")
    run=st.button("Run AI analysis",disabled=preview is None)
    st.markdown('</div>',unsafe_allow_html=True)

with right:
    st.markdown('<div class="card">',unsafe_allow_html=True)
    st.subheader("Analysis result")
    if run and preview is not None:
        try:
            with st.spinner("Analyzing image..."):
                model=load_model()
                arr=np.asarray(preview.resize(IMG_SIZE),dtype=np.float32)
                arr=np.expand_dims(arr,axis=0)
                # Training model already contains Rescaling(1./255).
                score=float(np.asarray(model.predict(arr,verbose=0)).reshape(-1)[0])
                idx=1 if score>=0.5 else 0
                label=CLASS_NAMES[idx]
                confidence=score if idx==1 else 1-score
            st.markdown(f'<div class="result"><div style="font-size:12px;color:#52736f;font-weight:800;letter-spacing:1px">CNN PREDICTED CLASS</div><h2>{label.title()}</h2><b>Confidence in predicted class: {confidence:.1%}</b></div>',unsafe_allow_html=True)
            st.progress(max(0.0,min(1.0,confidence)))
            st.caption(f"Raw sigmoid score for class 1 ({CLASS_NAMES[1]}): {score:.4f}")
        except Exception as e:
            st.error(f"Prediction failed: {e}")
    else:
        st.write("Upload an image and select **Run AI analysis** to see your model output.")
        st.caption("Your trained model file must be present in this repository.")
    st.markdown('</div>',unsafe_allow_html=True)

